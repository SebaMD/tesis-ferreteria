// Pure SQL generation from the versioned Drizzle snapshot. This module never connects.
const q = value => `"${String(value).replaceAll('"', '""')}"`;
export function snapshotDdl(snapshot) {
  const tables = Object.values(snapshot.tables), statements = [];
  for (const t of tables) {
    const columns = Object.values(t.columns).map(c => `${q(c.name)} ${c.type}${c.identity ? ' generated by default as identity' : ''}${c.default !== undefined ? ` default ${c.default}` : ''}${c.notNull ? ' not null' : ''}${c.primaryKey ? ' primary key' : ''}`);
    for (const pk of Object.values(t.compositePrimaryKeys)) columns.push(`constraint ${q(pk.name)} primary key (${pk.columns.map(q).join(',')})`);
    for (const u of Object.values(t.uniqueConstraints)) columns.push(`constraint ${q(u.name)} unique (${u.columns.map(q).join(',')})`);
    for (const c of Object.values(t.checkConstraints)) columns.push(`constraint ${q(c.name)} check (${c.value})`);
    statements.push(`create table ${q(t.name)} (${columns.join(',')})`);
  }
  for (const t of tables) for (const i of Object.values(t.indexes)) {
    const columns = i.columns.map(c => `${c.isExpression ? `(${c.expression})` : q(c.expression)} ${c.asc ? 'asc' : 'desc'} nulls ${c.nulls || 'last'}`);
    statements.push(`create ${i.isUnique ? 'unique ' : ''}index ${q(i.name)} on ${q(t.name)} using ${i.method} (${columns.join(',')})${i.where ? ` where ${i.where}` : ''}`);
  }
  for (const t of tables) for (const fk of Object.values(t.foreignKeys)) statements.push(`alter table ${q(t.name)} add constraint ${q(fk.name)} foreign key (${fk.columnsFrom.map(q).join(',')}) references ${q(fk.tableTo)} (${fk.columnsTo.map(q).join(',')}) on delete ${fk.onDelete} on update ${fk.onUpdate}`);
  return statements;
}
